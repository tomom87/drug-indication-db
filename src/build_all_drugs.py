def parse_iyakuhin() -> list[dict]:
    with open(IYAKUHIN_FILE, "rb") as f:
        raw = f.read()
    text = raw.decode("cp932", errors="replace")
    reader = csv.reader(io.StringIO(text))
    records = []
    for row in reader:
        if len(row) < 35 or row[1] != "Y":
            continue
        name = row[4]
        kana = row[6]
        yj_code = row[31] if len(row) > 31 else ""
        if not yj_code or len(yj_code) < 4:
            continue
        records.append({
            "name": name,
            "kana": kana,
            "yj_code": yj_code,
            "yakkou4": yj_code[:4],
        })
    return records


def find_byomei_code(cursor, name: str) -> str | None:
    cursor.execute("SELECT code FROM byomei WHERE name = ?", (name,))
    row = cursor.fetchone()
    if row:
        return row[0]
    cursor.execute("SELECT code, name FROM byomei WHERE name LIKE ?", (f"%{name}%",))
    rows = cursor.fetchall()
    if rows:
        best = min(rows, key=lambda r: len(r[1]))
        return best[0]
    return None


def extract_generic_name(brand_name: str) -> str:
    """販売名から一般名的な短縮名を生成."""
    # 規格部分を除去
    name = re.sub(r'[０-９0-9]+[．.]*[０-９0-9]*\s*[ｍＭmM][ｇＧgG].*', '', brand_name)
    name = re.sub(r'[０-９0-9]+[．.]*[０-９0-9]*\s*[％%].*', '', name)
    name = re.sub(r'\s*（.*）', '', name)
    name = re.sub(r'\s*\(.*\)', '', name)
    # 剤形を除去
    name = re.sub(r'(錠|カプセル|散|顆粒|細粒|シロップ|ドライシロップ|注射|点滴|液|テープ|パップ|ゲル|クリーム|軟膏|点眼|吸入|坐剤|注).*$', '', name)
    return name.strip()


def build_all():
    conn = sqlite3.connect(str(DB_PATH))
    c = conn.cursor()

    # 既存薬剤のYJコードを取得（手動キュレーション済み）
    c.execute("SELECT yj_code FROM drug")
    existing_yj = {row[0] for row in c.fetchall()}

    # 既存のindication yj_codesも取得
    c.execute("SELECT DISTINCT yj_code FROM indication")
    existing_indication_yj = {row[0] for row in c.fetchall()}

    # 医薬品マスター全件パース
    iyakuhin = parse_iyakuhin()
    print(f"医薬品マスター: {len(iyakuhin)} 件")

    # YJコードの先頭7桁でグルーピング（同一成分の規格違いをまとめる）
    seen_yj7 = set()
    new_drugs = []
    new_drug_count = 0
    new_indication_count = 0

    for item in iyakuhin:
        yj7 = item["yj_code"][:7]
        if yj7 in seen_yj7:
            continue
        seen_yj7.add(yj7)

        yakkou4 = item["yakkou4"]
        category_info = YAKKOU_MAP.get(yakkou4)
        if not category_info:
            # 3桁でも試す
            category_info = YAKKOU_MAP.get(yakkou4[:3] + "0")
        if not category_info:
            category = "その他"
            byomei_names = []
        else:
            category, byomei_names = category_info

        # この薬剤の代表名
        generic = extract_generic_name(item["name"])
        yj_code = f"ALL_{yj7}"

        # 既存の手動キュレーションデータと重複チェック
        if yj_code in existing_yj:
            continue

        # drug登録
        c.execute(
            "INSERT OR IGNORE INTO drug (yj_code, name, generic_name, category) VALUES (?, ?, ?, ?)",
            (yj_code, item["name"], generic, category),
        )
        new_drug_count += 1

        # brand_name登録
        c.execute(
            "INSERT OR IGNORE INTO brand_name (yj_code, brand_name, brand_kana) VALUES (?, ?, ?)",
            (yj_code, item["name"], item["kana"]),
        )

        # indication登録（薬効分類ベース）
        for byomei_name in byomei_names:
            byomei_code = find_byomei_code(c, byomei_name)
            if byomei_code:
                c.execute(
                    "INSERT OR IGNORE INTO indication (yj_code, byomei_code, indication_text, source) VALUES (?, ?, ?, ?)",
                    (yj_code, byomei_code, f"薬効分類: {category}", "yakkou_class"),
                )
                new_indication_count += 1

    conn.commit()

    # 統計
    c.execute("SELECT COUNT(*) FROM drug")
    total_drugs = c.fetchone()[0]
    c.execute("SELECT COUNT(*) FROM indication")
    total_indications = c.fetchone()[0]
    c.execute("SELECT COUNT(*) FROM brand_name")
    total_brands = c.fetchone()[0]

    print(f"新規追加薬剤: {new_drug_count}")
    print(f"新規追加マッピング: {new_indication_count}")
    print(f"DB総薬剤数: {total_drugs}")
    print(f"DB総マッピング数: {total_indications}")
    print(f"DB総販売名数: {total_brands}")

    conn.close()


if __name__ == "__main__":
    build_all()
